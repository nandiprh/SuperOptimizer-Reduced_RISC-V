#pragma once

#include "features.hpp"

// Generated model header: gradient-boosted regression trees exported from
// tools/train_model.py. When no trained model is available, predict_cycles()
// (in features.cpp) falls back to model_predict() below, which is a simple
// linear estimate: cycles ~= n_insns + dep_depth.

namespace sopt {

struct TreeNode {
  int feature_idx;  // -1 => leaf
  double threshold;
  int left;         // child node index, -1 if leaf
  int right;        // child node index, -1 if leaf
  double value;     // leaf value
};

struct GBDTModel {
  std::vector<TreeNode> nodes;
  int num_trees = 0;
  // roots[i] = index of root node for tree i (roots are contiguous in `nodes`)
  std::vector<int> roots;
  double base = 0.0; // initial prediction (mean of the training labels)
};

// Trained model instance (generated by tools/train_model.py).
// Keep the generated arrays in a separate header so retraining does not touch
// this hand-written inference code.
#include "model_data.hpp"

// Evaluate the boosted tree ensemble on `features`.
inline double model_predict(const double* features) {
  if (g_model.nodes.empty()) {
    // Fallback: no trained model. Linear estimate.
    return features[0] + features[22]; // n_insns + dep_depth
  }
  double sum = g_model.base;
  for (int root : g_model.roots) {
    int node = root;
    while (node >= 0 && g_model.nodes[node].feature_idx >= 0) {
      int fi = g_model.nodes[node].feature_idx;
      if (features[fi] <= g_model.nodes[node].threshold)
        node = g_model.nodes[node].left;
      else
        node = g_model.nodes[node].right;
    }
    if (node >= 0) sum += g_model.nodes[node].value;
  }
  return sum;
}

} // namespace sopt
